    public void searchAccounts(MainCallback<ResponseListObj<UserResponse>> callback, String keyword) {
        AccountAutoCompleteRequest request = new AccountAutoCompleteRequest();
        request.setKeyword(keyword);
        request.setIgnoreUserId(getUserId());
        Map<String, Object> query = RequestToMapConverter.convert(request);
        compositeDisposable.add(repository.getMasterApiService().getUserAutoComplete(query)
                .subscribeOn(Schedulers.io())
                .observeOn(AndroidSchedulers.mainThread())
                .retryWhen(throwable ->
                        throwable.flatMap((Function<Throwable, ObservableSource<?>>) throwable1 -> {
                            if (NetworkUtils.checkNetworkError(throwable1)) {
                                return application.showDialogNoInternetAccess();
                            } else {
                                return Observable.error(throwable1);
                            }
                        })
                )
                .subscribe(
                        response -> {
                            if (response.isResult()) {
                                callback.doSuccess(response.getData());
                            } else {
                                callback.doFail();
                            }
                        }, throwable -> {
                            Timber.e(throwable);
                            callback.doError(throwable);
                        }
                )
        );
    }

